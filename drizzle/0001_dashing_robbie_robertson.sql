CREATE TABLE `briefs` (
	`id` int AUTO_INCREMENT NOT NULL,
	`briefId` varchar(32) NOT NULL,
	`ownerId` int NOT NULL,
	`status` enum('draft','submitted','needs-info','accepted','scoped','in-production','ready-for-review','changes-requested','delivered','cancelled') NOT NULL DEFAULT 'draft',
	`idea` text NOT NULL,
	`projectType` varchar(120),
	`audience` text,
	`scope` text,
	`budget` varchar(120),
	`targetDate` varchar(120),
	`structuredBrief` text NOT NULL,
	`aiNotes` text NOT NULL,
	`openQuestions` text NOT NULL,
	`termsVersion` varchar(32),
	`acceptedAt` timestamp,
	`acceptedBy` int,
	`consentScope` text,
	`paymentStatus` enum('unpaid','processing','paid','failed') NOT NULL DEFAULT 'unpaid',
	`paymentIntentId` varchar(255),
	`paymentAmount` int,
	`paymentCurrency` varchar(3) NOT NULL DEFAULT 'usd',
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `briefs_id` PRIMARY KEY(`id`),
	CONSTRAINT `briefs_briefId_unique` UNIQUE(`briefId`)
);
